"""MMD標準ボーン構造の定義。

各ボーンの親子関係を辞書として保持する。センターや左右の足ＩＫのように、
複数のボーンが直接センターにぶら下がる構造(足ＩＫはFKの足チェーンとは別系統で
センター直下に配置される)など、実際のMMD標準モデルの一般的な構成に沿っている。

IK系ボーン名は、実際に配布されているMMDモデルの命名慣習に合わせて全角
(ＩＫ)で統一している。半角表記のモデルと比較する場合は
bones.name_utils.bone_names_equal() を使うこと。
"""

# ボーン名 -> 親ボーン名。値がNoneのボーンはルート(親を持たない)。
STANDARD_BONE_PARENTS: dict[str, str | None] = {
    "センター": None,
    "上半身": "センター",
    "下半身": "センター",
    "首": "上半身",
    "頭": "首",
    # 左腕
    "左肩": "上半身",
    "左腕": "左肩",
    "左ひじ": "左腕",
    "左手首": "左ひじ",
    # 右腕
    "右肩": "上半身",
    "右腕": "右肩",
    "右ひじ": "右腕",
    "右手首": "右ひじ",
    # 左足(FKチェーン)
    "左足": "下半身",
    "左ひざ": "左足",
    "左足首": "左ひざ",
    # 左足(IKチェーン。センター直下に独立して配置される)
    "左足ＩＫ": "センター",
    "左つま先ＩＫ": "左足ＩＫ",
    # 右足(FKチェーン)
    "右足": "下半身",
    "右ひざ": "右足",
    "右足首": "右ひざ",
    # 右足(IKチェーン)
    "右足ＩＫ": "センター",
    "右つま先ＩＫ": "右足ＩＫ",
}


def get_parent(bone_name: str) -> str | None:
    """指定したボーンの親ボーン名を返す。ルートボーンの場合はNoneを返す。"""
    return STANDARD_BONE_PARENTS[bone_name]


def get_children(bone_name: str) -> list[str]:
    """指定したボーンの直接の子ボーン名一覧を返す。"""
    return [name for name, parent in STANDARD_BONE_PARENTS.items() if parent == bone_name]
