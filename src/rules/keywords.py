"""ルールベース解析器が参照するキーワード辞書。

src/rules/parser.py は、文章を形態素解析して得た各トークンの基本形
(base_form)をここに定義したキーワードと照合する。基本形を使うことで、
「振る」「振ります」「振って」のような活用の違いを吸収できる。
"""

# 動作キーワード(基本形) -> action タグ
# NOTE: シンプルな単語一致によるルールベース実装のため、「首を振る」のような
# 文脈による意味の違いまでは考慮していない(最初のプロトタイプとしての割り切り)。
ACTION_KEYWORDS: dict[str, str] = {
    "振る": "wave",  # 例: 手を振る
    "お辞儀": "bow",  # 例: お辞儀する
    "振り返る": "turn_back",  # 例: 振り返る
    "頷く": "nod",  # 例: 頷く、うなずく
    "座る": "sit",  # 例: 座る
}

# 感情キーワード(基本形) -> (emotion タグ, 強度への加算量)
# 「元気」のように、感情そのものが強度のニュアンスを含む語は加算量を持たせている。
EMOTION_KEYWORDS: dict[str, tuple[str, float]] = {
    "元気": ("happy", 0.3),
    "嬉しい": ("happy", 0.2),
    "楽しい": ("happy", 0.2),
    "丁寧": ("polite", 0.0),
    "恥ずかしい": ("shy", -0.2),
    "悲しい": ("sad", -0.1),
    "怒る": ("angry", 0.2),
}

# 強度を直接調整する表現(基本形) -> 強度への加算量
INTENSITY_KEYWORDS: dict[str, float] = {
    "もっと": 0.2,
    "すごく": 0.3,
    "とても": 0.3,
    "少し": -0.2,
    "ちょっと": -0.2,
    "控えめ": -0.3,
    "大きい": 0.2,  # 例: 大きく手を振る(「大きく」の基本形は「大きい」)
    "小さい": -0.2,
}

# 強度のデフォルト値(感情・強度キーワードが見つからない場合の基準値)
BASE_INTENSITY = 0.5
MIN_INTENSITY = 0.0
MAX_INTENSITY = 1.0
